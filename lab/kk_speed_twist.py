"""kk_speed_twist.py - TASK 2: a DYNAMIC twist field with its OWN stiffness K (not gravity's).

1+1 D (x ring of L sites) x hidden circle (N sites), hop speed c_w along w. Two charged packets, each
its own walker. Every tick the time-twist phi_j(x) generated by packet j is solved from Gauss' law
K phi'' = -rho_j (open line, exact in 1+1 D: the gauge field has no propagating modes here), and the
OTHER packet slides around the hidden circle by phi_j (phase n phi / R). No self-interaction (debt).
Measured for every run, independently:
  F = d<k>/dt  (force: should be n1 n2 / (2 K R^2), independent of c_w)
  M from the trajectory x(t) = x0 + (sqrt(M^2 + (F t)^2) - M) / F  (inertia: should be the rest
    energy sqrt(theta^2 + (c_w n / R)^2), independent of K)
Seeded/deterministic. Writes out/kk_speed_twist.json and out/kk_speed_twist_tmp.npz. Run from lab/.
"""
import json, time
import numpy as np
from scipy.optimize import curve_fit
import kk_speed_core as S

t0 = time.time()
L, N, th, T, sig, d = 2048, 16, 0.02, 300, 100.0, 700
R = N / (2 * np.pi)
runs = [  # (n1, n2, c_w, K)
    (1, 1, 0.10, 1000.0), (1, -1, 0.10, 1000.0), (2, 1, 0.10, 1000.0),
    (1, 1, 0.05, 1000.0), (1, 1, 0.20, 1000.0), (1, 1, 0.10, 4000.0), (1, 1, 0.10, 250.0)]
out = {"params": dict(L=L, N=N, R=R, theta=th, ticks=T, sigma=sig, separation=d), "runs": []}
tracks = {}
for (n1, n2, cw, Kst) in runs:
    x1, x2 = L // 2 - d // 2, L // 2 + d // 2
    p1 = S.packet_cw(L, 1, N, th, n1, cw=cw, sigma=sig, center=(x1, 0))
    p2 = S.packet_cw(L, 1, N, th, n2, cw=cw, sigma=sig, center=(x2, 0))
    W1 = S.KKWalkCw(L, 1, N, th, cw=cw); W2 = S.KKWalkCw(L, 1, N, th, cw=cw)
    # inertia expected for a PACKET = its mean energy <sqrt(M_rest^2 + k^2)> (k-spread of the packet)
    Fk = np.sum(np.abs(np.fft.fft(p1, axis=1))**2, axis=(0, 2, 3)); kk = 2 * np.pi * np.fft.fftfreq(L)
    Mrest = S.rest_energy(N, th, n1, cw)
    Epk = float(np.sum(Fk * np.sqrt(Mrest**2 + kk**2)) / Fk.sum())
    tr = np.empty((T + 1, 4))
    for t in range(T + 1):
        a, ka = S.mean_x_k(p1); b, kb = S.mean_x_k(p2)
        tr[t] = (a, ka, b, kb)
        if t == T:
            break
        r1 = S.charge_density(p1, N)[:, 0]; r2 = S.charge_density(p2, N)[:, 0]
        W1.phi = S.gauss_1d(r2, Kst)[:, None]        # packet 1 feels only packet 2's twist
        W2.phi = S.gauss_1d(r1, Kst)[:, None]
        p1 = W1.tick(p1); p2 = W2.tick(p2)
    tt = np.arange(T + 1)
    # force on the LEFT packet: positive = pushed towards +x (attraction), negative = repulsion
    F = np.polyfit(tt, tr[:, 1], 1)[0]
    Fpred = -n1 * n2 / (2 * Kst * R**2)
    xs = tr[:, 0] - tr[0, 0]
    f = lambda t, M: (np.sqrt(M**2 + (F * t)**2) - M) / F
    M = float(curve_fit(f, tt, xs, p0=[0.05])[0][0])
    Mpred = Mrest
    Mcont = float(np.sqrt(th**2 + (cw * n1 / R)**2))
    row = dict(n1=n1, n2=n2, cw=cw, K=Kst, F_meas=F, F_pred=Fpred, F_rel_err=(F - Fpred) / Fpred,
               M_meas=M, M_rest_walk=Mpred, E_packet=Epk, M_vs_Epacket_rel=(M - Epk) / Epk, M_continuum=Mcont, M_rel_err=(M - Mpred) / Mpred,
               q_over_M=(abs(n1) / R / np.sqrt(Kst)) / M, final_v=float((xs[-1] - xs[-2])),
               alpha_eff=1.0 / (4 * np.pi * Kst * R**2))
    out["runs"].append(row)
    tracks[f"{n1}_{n2}_{cw}_{Kst}"] = tr
    print(f"n1={n1:+d} n2={n2:+d} c_w={cw:4.2f} K={Kst:6.0f}: F = {F:+.4e} (pred {Fpred:+.4e}, {100*(F-Fpred)/Fpred:+.2f}%)"
          f"   M = {M:.5f} (rest energy on the walk {Mpred:.5f}, {100*(M-Mpred)/Mpred:+.2f}%; packet <E> {Epk:.5f}, {100*(M-Epk)/Epk:+.2f}%)  alpha_eff = {row['alpha_eff']:.2e}")
np.savez("out/kk_speed_twist_tmp.npz", **tracks)
out["time_s"] = time.time() - t0
json.dump(out, open("out/kk_speed_twist.json", "w"), indent=1)
print("time %.1f s" % out["time_s"])
